import AppKit
import os

extension NSPasteboard.PasteboardType {
  static let transient = Self("org.nspasteboard.TransientType")
  static let concealed = Self("org.nspasteboard.ConcealedType")
  static let autoGenerated = Self("org.nspasteboard.AutoGeneratedType")
}

typealias PasteboardSnapshot = [[NSPasteboard.PasteboardType: Data]]

let insertLog = Logger(subsystem: "dev.junya.sokki", category: "insert")

@MainActor
enum PasteboardSnapshotter {
  static func snapshot(_ pasteboard: NSPasteboard) -> PasteboardSnapshot {
    (pasteboard.pasteboardItems ?? []).map { item in
      var entry: [NSPasteboard.PasteboardType: Data] = [:]
      for type in item.types {
        if let data = item.data(forType: type) { entry[type] = data }
      }
      return entry
    }
  }

  static func restore(_ snapshot: PasteboardSnapshot, to pasteboard: NSPasteboard) {
    pasteboard.clearContents()
    let items = snapshot.map { entry in
      let item = NSPasteboardItem()
      for (type, data) in entry { item.setData(data, forType: type) }
      return item
    }
    if !items.isEmpty { pasteboard.writeObjects(items) }
  }
}

/// Supplies the text lazily so the target app's read doubles as a receipt.
@MainActor
final class PromiseProvider: NSObject {
  let text: String
  private(set) var receivedAt: ContinuousClock.Instant?

  init(text: String) {
    self.text = text
  }
}

extension PromiseProvider: @MainActor NSPasteboardTypeOwner {
  func pasteboard(_ sender: NSPasteboard, provideDataForType type: NSPasteboard.PasteboardType) {
    guard type == .string else { return }
    if receivedAt == nil { receivedAt = .now }
    sender.setString(text, forType: .string)
  }
}

/// One clipboard round trip: snapshot, write the promise, and later restore.
@MainActor
final class PasteSession {
  let pasteboard: NSPasteboard
  let saved: PasteboardSnapshot
  let provider: PromiseProvider
  let changeCount: Int

  init(text: String, pasteboard: NSPasteboard) {
    self.pasteboard = pasteboard
    saved = PasteboardSnapshotter.snapshot(pasteboard)
    provider = PromiseProvider(text: text)
    pasteboard.declareTypes([.string, .transient, .concealed, .autoGenerated], owner: provider)
    for marker: NSPasteboard.PasteboardType in [.transient, .concealed, .autoGenerated] {
      pasteboard.setData(Data(), forType: marker)
    }
    changeCount = pasteboard.changeCount
  }

  /// Restores the snapshot unless someone else wrote to the pasteboard since our write.
  @discardableResult
  func restoreIfUnchanged() -> Bool {
    guard pasteboard.changeCount == changeCount else { return false }
    PasteboardSnapshotter.restore(saved, to: pasteboard)
    return true
  }

  func finish(postedAt: ContinuousClock.Instant, receiptTimeout: Duration = .milliseconds(1500))
    async
  {
    let deadline = postedAt + receiptTimeout
    while provider.receivedAt == nil, ContinuousClock.now < deadline {
      try? await Task.sleep(for: .milliseconds(10))
    }
    if let receivedAt = provider.receivedAt {
      let ms = (receivedAt - postedAt).milliseconds
      insertLog.debug("receipt after \(ms, format: .fixed(precision: 1)) ms")
      // The reader may still be pulling remaining data right after the first request.
      try? await Task.sleep(for: .milliseconds(60))
    } else {
      insertLog.debug(
        "no receipt within \(receiptTimeout.milliseconds, format: .fixed(precision: 0)) ms")
    }
    let restored = restoreIfUnchanged()
    insertLog.debug("clipboard \(restored ? "restored" : "left alone: changed by someone else")")
  }
}

extension Duration {
  var milliseconds: Double {
    let (seconds, attoseconds) = components
    return Double(seconds) * 1000 + Double(attoseconds) / 1e15
  }
}
